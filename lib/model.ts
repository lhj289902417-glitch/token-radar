// Token Radar's model, version radar-2 ("comparables").
//
// One sealed snapshot in, one ranked board out. The board ranks every
// pre-token protocol the watchlist rule would keep: the 40 on the watchlist
// plus every other pre-token protocol below the floor that is not a wrapped,
// staked or bridged product of a token that already trades, not a versioned
// pool and not an exchange. Live-token protocols are kept apart and shown
// with the market's own market cap, never mixed into the ranking.
//
// Implied value is priced from the snapshot's own live market, not from a
// flat multiple and never from a list of names:
//
//   comparable multiple = the median market-cap / TVL of the live-token
//     protocols in the same category (at least 3 live names with a measurable
//     market cap above zero, else the whole market's median), shrunk 70/30
//     toward the market median and clamped to [0.05, 1.00]
//   growth     = 1 + clamp(change_7d, -60, 120) / 100 * 0.5
//   maturity   = 0.6 + min(age_days, 1095) / 1095 * 0.4   (age unknown: 365)
//   breadth    = 1 + 0.02 * min(chains - 1, 5)            (more chains, wider reach)
//   implied    = max(1, round(tvl_usd * multiple * growth * maturity * breadth))
//
// A category whose live names trade richly against their TVL (Dexs) prices
// its pre-token names richly; a category whose live names trade thinly
// (Lending) prices its pre-token names thinly. The same function scores
// every row, and the dashboard shows each row's multiple beside the live
// names it came from, so the claim can be checked.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

